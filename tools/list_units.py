#!/usr/bin/env python3
"""
List candidate units to decompile for the Release_eu retail build.

The retail DOL is already split, so every address range not claimed by
splits.txt is an autogenerated object under build/Release_eu/obj/auto_*.o.
Those are the code the project has not decompiled yet. This script prints them
with their address range and size so a contributor can pick a target.

Usage:
    python tools/list_units.py                     # top candidates, largest first
    python tools/list_units.py --min 0x400 --max 0x2000
    python tools/list_units.py --name-prefix fn_8
    python tools/list_units.py --section .text --min 0x800
"""

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

AUTO = re.compile(r"^auto_(\d+)_([0-9A-Fa-f]+)_(\w+)$")


def load_units(config_path: Path):
    data = json.loads(config_path.read_text(encoding="utf-8"))
    units = []
    for u in data.get("units", []):
        name = u["name"]
        if not name.startswith("auto_"):
            continue
        units.append(u)
    return units


def object_size(objdump: Path, path: Path, sections):
    if not path.is_file():
        return 0
    out = subprocess.run([str(objdump), "-h", str(path)], stdout=subprocess.PIPE,
                         stderr=subprocess.DEVNULL, text=True).stdout
    total = 0
    for line in out.splitlines():
        parts = line.split()
        if len(parts) >= 5 and parts[0].isdigit() and parts[1] in sections:
            total += int(parts[2], 16)
    return total


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", type=Path, default=Path("build/Release_eu/config.json"))
    ap.add_argument("--objdump", type=Path, default=Path("build/binutils/powerpc-eabi-objdump.exe"))
    ap.add_argument("--section", default=".text",
                    help="section to measure: .text/.rodata/.data/.bss (default .text)")
    ap.add_argument("--min", type=lambda v: int(v, 0), default=0x100)
    ap.add_argument("--max", type=lambda v: int(v, 0), default=0x100000)
    ap.add_argument("--name-prefix", default="")
    ap.add_argument("--limit", type=int, default=60)
    args = ap.parse_args()

    if not args.config.is_file():
        print("error: %s missing. Run configure.py + ninja first." % args.config, file=sys.stderr)
        return 1

    units = load_units(args.config)
    rows = []
    for u in units:
        name = u["name"]
        if args.name_prefix and not name.startswith(args.name_prefix):
            continue
        obj = Path(u["object"])
        size = object_size(args.objdump, obj, {args.section})
        if not (args.min <= size <= args.max):
            continue
        # Derive address range from the name: auto_<section>_<addr>_<sect>
        parts = name.split("_", 3)
        addr = parts[2] if len(parts) > 2 else "?"
        sect = parts[3] if len(parts) > 3 else args.section
        rows.append((size, name, obj.as_posix(), sect))

    rows.sort(reverse=True)
    print("%-9s %-34s %-12s %s" % ("size", "unit", "section", "object"))
    for size, name, obj, sect in rows[: args.limit]:
        print("%8d 0x%-6X %-34s %-12s %s" % (size, size, name, sect, obj))
    print("\n%d candidates in range 0x%X..0x%X (showing %d)" % (
        len(rows), args.min, args.max, min(len(rows), args.limit)))
    return 0


if __name__ == "__main__":
    sys.exit(main())